import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const migrationsDirectory = new URL("supabase/migrations/", root);
const applicationTypesUrl = new URL("src/types/database.ts", root);
const generatedUrl = new URL("src/types/database-contract.generated.ts", root);

function uniqueSorted(values) {
  return [...new Set(values)].sort();
}

function names(source, expression) {
  return uniqueSorted([...source.matchAll(expression)].map((match) => match[1]));
}

function between(source, start, end) {
  const from = source.indexOf(start);
  const to = source.indexOf(end, from + start.length);
  if (from < 0 || to < 0) {
    throw new Error(`Unable to locate TypeScript contract block: ${start}`);
  }
  return source.slice(from + start.length, to);
}

export function extractMigrationContract(sql) {
  const withoutComments = sql
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/--.*$/gm, "");

  return {
    tables: names(
      withoutComments,
      /\bcreate\s+table\s+(?:if\s+not\s+exists\s+)?public\.([a-zA-Z_][a-zA-Z0-9_]*)/gi,
    ),
    functions: names(
      withoutComments,
      /\bcreate\s+(?:or\s+replace\s+)?function\s+public\.([a-zA-Z_][a-zA-Z0-9_]*)\s*\(/gi,
    ),
    enums: names(
      withoutComments,
      /\bcreate\s+type\s+public\.([a-zA-Z_][a-zA-Z0-9_]*)\s+as\s+enum\b/gi,
    ),
  };
}

export function extractApplicationTypeContract(source) {
  const tablesBlock = between(source, "    Tables: {", "    Views:");
  const functionsBlock = between(source, "    Functions: {", "    Enums:");
  const enumsBlock = between(source, "    Enums: {", "    CompositeTypes:");

  return {
    tables: names(tablesBlock, /^      ([a-zA-Z_][a-zA-Z0-9_]*):\s*Table</gm),
    functions: names(functionsBlock, /^      ([a-zA-Z_][a-zA-Z0-9_]*):\s*\{/gm),
    enums: names(enumsBlock, /^      ([a-zA-Z_][a-zA-Z0-9_]*):/gm),
  };
}

function assertSubset(label, typed, schema) {
  const available = new Set(schema);
  const missing = typed.filter((name) => !available.has(name));
  if (missing.length) {
    throw new Error(
      `Database TypeScript contract references missing ${label}: ${missing.join(", ")}`,
    );
  }
}

function render(contract) {
  return `// AUTO-GENERATED by scripts/generate-schema-contract.mjs.
// Repository migrations are authoritative. Do not edit this file by hand.

export const databaseSchemaContract = ${JSON.stringify(contract,null,2)} as const;

export type DatabaseSchemaContract = typeof databaseSchemaContract;
`;
}

async function expectedGeneratedSource() {
  const migrationFiles = (await readdir(migrationsDirectory))
    .filter((name) => name.endsWith(".sql"))
    .sort();

  const chunks = [];
  const digest = createHash("sha256");
  for (const filename of migrationFiles) {
    const content = await readFile(new URL(filename, migrationsDirectory), "utf8");
    digest.update(filename);
    digest.update("\0");
    digest.update(content);
    digest.update("\0");
    chunks.push(content);
  }

  const appTypes = await readFile(applicationTypesUrl, "utf8");
  const migrationContract = extractMigrationContract(chunks.join("\n"));
  const applicationContract = extractApplicationTypeContract(appTypes);

  assertSubset("tables", applicationContract.tables, migrationContract.tables);
  assertSubset("functions", applicationContract.functions, migrationContract.functions);
  assertSubset("enums", applicationContract.enums, migrationContract.enums);

  return render({
    migrationSha256: digest.digest("hex"),
    applicationTypesSha256: createHash("sha256").update(appTypes).digest("hex"),
    migrationFiles,
    schema: migrationContract,
    applicationTypes: applicationContract,
  });
}

function mismatchError() {
  return new Error(
    "Database schema/type contract drift detected. Run npm run schema:generate and review the generated diff.",
  );
}

async function checkCurrent(expected) {
  let actual = "";
  try {
    actual = await readFile(generatedUrl, "utf8");
  } catch {
    throw mismatchError();
  }
  if (actual !== expected) throw mismatchError();
}

const mode = process.argv[2] ?? "--check";
const expected = await expectedGeneratedSource();

if (mode === "--write") {
  await writeFile(generatedUrl, expected, "utf8");
  process.stdout.write("Database schema/type contract generated.\n");
} else if (mode === "--check") {
  await checkCurrent(expected);
  process.stdout.write("Database schema/type contract is current.\n");
} else if (mode === "--prove-drift") {
  let detected = false;
  try {
    const current = await readFile(generatedUrl, "utf8");
    if ((current + "\n// deliberate mismatch\n") !== expected) {
      throw mismatchError();
    }
  } catch (error) {
    detected = error instanceof Error && /drift detected/.test(error.message);
  }
  if (!detected) {
    throw new Error("Schema drift detector failed to reject a deliberate mismatch.");
  }
  process.stdout.write("Deliberate schema/type mismatch was rejected as expected.\n");
} else {
  throw new Error(`Unknown schema contract mode: ${mode}`);
}
